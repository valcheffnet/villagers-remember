def main():
    for i, lang in enumerate(("en_us", "bg_bg")):
        path = os.path.join(LANG, lang + ".json")
        d = json.load(open(path, encoding="utf-8"))
        for k in [k for k in d if k.startswith("lore.") or k.startswith("order.")]:
            del d[k]
        for prof, lines in REFORGE.items():
            d["lore." + prof + ".reforge"] = lines[i]
        for name, (en_name, bg_name, en_lore, bg_lore) in ORDERS.items():
            d["order." + name] = (en_name, bg_name)[i]
            d["lore.order." + name] = (en_lore, bg_lore)[i]
        for prof, lines in LORE.items():
            for suffix, texts in lines.items():
                d[f"lore.{prof}.{suffix}"] = texts[i]
        open(path, "w", encoding="utf-8").write(json.dumps(d, ensure_ascii=False, indent="\t") + "\n")
    print(sum(len(v) for v in LORE.values()), "lore lines per language")


if __name__ == "__main__":
    main()
